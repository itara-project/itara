fn serialize_return_i64(serializer_id: &str, value: i64) -> Vec<u8> {
    match serializer_id {
        "json" => json::serialize(&value),
        unknown => panic!("[CalculatorDispatcher] serialize_return: unsupported serializer '{}'", unknown),
    }
}
