// ── Generated dispatcher (future: #[itara_component] macro output) ────────────

pub fn calculator_dispatcher(
    component:     &'static dyn CalculatorService,
    serializer_id: String,
) -> Dispatcher {
    Box::new(move |method: &str, args: &[u8]| -> Vec<u8> {
        match method {
            "add" => {
                let (a, b) = deserialize_args_add(&serializer_id, args);
                let result = component.add(a, b);
                serialize_return_i64(&serializer_id, result)
            }
            "multiply" => {
                let (a, b) = deserialize_args_multiply(&serializer_id, args);
                let result = component.multiply(a, b);
                serialize_return_i64(&serializer_id, result)
            }
            unknown => panic!("[CalculatorDispatcher] unknown method: '{}'", unknown),
        }
    })
}
 
// ── Serialization dispatch ────────────────────────────────────────────────────
//
// One function per method per direction. Each function matches on the
// serializer id and dispatches to the correct format implementation.
// No intermediate format — each arm works directly with the typed values.
//
// Future: generated by the macro for the serializers declared in [serializers]
// of the .itara metadata file.
 
fn serialize_args_add(serializer_id: &str, a: i64, b: i64) -> Vec<u8> {
    match serializer_id {
        "json" => json::serialize(&[a, b]),
        unknown => panic!("[CalculatorProxy] add: unsupported serializer '{}'", unknown),
    }
}
 
fn serialize_args_multiply(serializer_id: &str, a: i64, b: i64) -> Vec<u8> {
    match serializer_id {
        "json" => json::serialize(&[a, b]),
        unknown => panic!("[CalculatorProxy] multiply: unsupported serializer '{}'", unknown),
    }
}
 
fn deserialize_return_i64(serializer_id: &str, bytes: &[u8]) -> i64 {
    match serializer_id {
        "json" => json::deserialize::<i64>(bytes),
        unknown => panic!("[CalculatorProxy] deserialize_return: unsupported serializer '{}'", unknown),
    }
}
 
fn deserialize_args_add(serializer_id: &str, bytes: &[u8]) -> (i64, i64) {
    match serializer_id {
        "json" => { let vals: [i64; 2] = json::deserialize(bytes); (vals[0], vals[1]) }
        unknown => panic!("[CalculatorDispatcher] add: unsupported serializer '{}'", unknown),
    }
}
 
